'use strict';
// Sestavi casparcg.config iz nastavitev aplikacije.
//
// Kanal 1 = PROGRAM (to gre na izhode).
// Kasneje: kanal 2 = PREVIEW (samo za monitor v vmesniku).

const VIDEO_MODES = {
  '1080p5000': '1080p 50',
  '1080p2500': '1080p 25',
  '1080i5000': '1080i 50',
  '1080p3000': '1080p 30',
  '1080p2997': '1080p 29,97',
  '1080p6000': '1080p 60',
  '1080p5994': '1080p 59,94',
};

function xmlEscape(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function p(path) {
  // CasparCG pričakuje poti s poševnico na koncu.
  let s = String(path).replace(/\\/g, '/');
  if (!s.endsWith('/')) s += '/';
  return xmlEscape(s);
}

/**
 * Screen izhod. Zaslon je vedno "borderless" okno točno čez cel izbran
 * zaslon (to je zanesljivejše od pravega celozaslonskega načina, ki v
 * knjižnici SFML deluje le na glavnem zaslonu).
 */
function screenConsumer({ display, keyOnly = false, name, windowedTest = false, testX = 40, delayFrames = 0 }) {
  const lines = ['<screen>'];
  if (windowedTest) {
    // Testni način: navadno okno na glavnem zaslonu, 960×540.
    lines.push('<device>1</device>', '<windowed>true</windowed>', '<borderless>false</borderless>',
      '<width>960</width>', '<height>540</height>', `<x>${testX}</x>`, '<y>40</y>');
  } else {
    lines.push(
      `<device>${display.index + 1}</device>`,
      '<windowed>true</windowed>',
      '<borderless>true</borderless>',
      '<always-on-top>true</always-on-top>',
      `<x>${display.offsetX || 0}</x>`, `<y>${display.offsetY || 0}</y>`,
      `<width>${display.width}</width>`, `<height>${display.height}</height>`,
      '<interactive>false</interactive>'
    );
  }
  lines.push(`<key-only>${keyOnly ? 'true' : 'false'}</key-only>`);
  lines.push('<stretch>uniform</stretch>');
  lines.push('<vsync>true</vsync>');
  if (delayFrames > 0) lines.push(`<delay>${Math.round(delayFrames)}</delay>`);
  if (name) lines.push(`<name>${xmlEscape(name)}</name>`);
  lines.push('</screen>');
  return lines.join('\n                    ');
}

/** Ime naprave, kot ga pozna OpenAL v CasparCG ("OpenAL Soft on <ime v Windows>"). */
function openAlName(name) {
  if (!name) return name;
  return /^openal soft on /i.test(name) ? name : `OpenAL Soft on ${name}`;
}

/** Iz vrstic dnevnika CasparCG prebere seznam zvočnih naprav (izpiše ga ob napačnem imenu). */
function parseOpenAlDevices(lines) {
  const out = [];
  let inside = false;
  for (const raw of lines) {
    const line = raw.replace(/^.*?\[info\]\s*/, '').trim();
    if (/^-+ OpenAL Devices -+$/.test(line)) {
      if (inside) break;
      inside = true;
      continue;
    }
    if (inside && line) out.push(line.replace(/^OpenAL Soft on /i, ''));
  }
  return out;
}

/**
 * @param {object} o
 * @param {string} o.videoMode
 * @param {object[]} o.screens  [{display, keyOnly, name, windowedTest}]
 * @param {string|null} o.audioDevice  ime naprave ali null za privzeto; false = brez zvoka
 * @param {object} o.paths {media, log, data, template, htmlCache}
 * @param {number} o.amcpPort
 */
function audioDelay(o) {
  const av = Math.round(o.audioDelayFrames || 0);
  return av > 0 ? `\n                        <delay>${av}</delay>` : '';
}

function buildConfig(o) {
  const consumers = [];
  // Zamik zvoka: pozitiven = zvok kasneje (zakasnimo zvok), negativen = slika kasneje (zakasnimo sliko).
  const av = Math.round(o.audioDelayFrames || 0);
  for (const s of o.screens) consumers.push(screenConsumer({ ...s, delayFrames: av < 0 ? -av : 0 }));
  if (o.audioDevice !== false) {
    if (o.audioDevice) {
      consumers.push(`<system-audio>\n                        <device-name>${xmlEscape(openAlName(o.audioDevice))}</device-name>${audioDelay(o)}\n                    </system-audio>`);
    } else {
      consumers.push(`<system-audio>${audioDelay(o)}\n                    </system-audio>`);
    }
  }

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Playout on every engine start. Manual changes are overwritten. -->
<configuration>
    <paths>
        <media-path>${p(o.paths.media)}</media-path>
        <log-path>${p(o.paths.log)}</log-path>
        <data-path>${p(o.paths.data)}</data-path>
        <template-path>${p(o.paths.template)}</template-path>
    </paths>
    <log-level>info</log-level>
    <channels>
        <channel>
            <video-mode>${xmlEscape(o.videoMode)}</video-mode>
            <consumers>
                    ${consumers.join('\n                    ')}
            </consumers>
        </channel>
        <channel>
            <!-- PREVIEW: brez izhodov, samo monitor v aplikaciji -->
            <video-mode>${xmlEscape(o.videoMode)}</video-mode>
            <consumers />
        </channel>
    </channels>
    <controllers>
        <tcp>
            <port>${o.amcpPort}</port>
            <protocol>AMCP</protocol>
        </tcp>
    </controllers>
    <osc>
        <default-port>${o.oscPort || 6250}</default-port>
        <disable-send-to-amcp-clients>true</disable-send-to-amcp-clients>
        <predefined-clients>
            <predefined-client>
                <address>127.0.0.1</address>
                <port>${o.oscPort || 6250}</port>
            </predefined-client>
        </predefined-clients>
    </osc>
    <html>
        <cache-path>${p(o.paths.htmlCache)}</cache-path>
    </html>
</configuration>
`;
}

module.exports = { buildConfig, VIDEO_MODES, openAlName, parseOpenAlDevices };
